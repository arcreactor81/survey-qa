// entry, never by editing the harness.
//
// Each entry is a single exact-string replacement expressing ONE small semantic
// change. `find` MUST occur exactly once in `file` — run-mutations.mjs --verify
// enforces that, so a gate that is renamed or deleted surfaces as catalogue
// drift instead of silently dropping out of the net.
//
// Fields
//   id           stable identifier, "<MODULE>-<GATE>"; results are keyed on it
//   file         repo-relative path of the module under test
//   gate         the guarantee this mutation removes, in plain language

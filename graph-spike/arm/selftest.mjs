#!/usr/bin/env node
/**
 * SELF-TEST — evidence that Arm B's guards CAN FAIL.
 *
 * CLAUDE.md, on this repository's own recurring bug:
 *
 *     "Beware the check that cannot fail. This repo has repeatedly shipped tests and gates
 *      that were structurally incapable of failing […] New gates should ship with evidence
 *      they can fail — a mutation, a negative fixture, or both."
 *
 * On the branching corpus every leak guard reports `firedTimes: 0`, and it reports that
 * HONESTLY — the corpus manifest states piping sources, carry-forward sources and
 * randomisation, so none of the three conditions arises. But "did not fire because it did
 * not apply" and "cannot fire" look identical from a single green run. This file
 * separates them.
 *
 * Two halves:
 *
 *  A. UNIT — synthetic IRs and findings that make each leak guard and each basis gate fire.
 *  B. LIVE — six synthetic HTML pages served over real HTTP and driven through a real
 *     headless Chrome, each violating exactly one declared platform assumption. This is
 *     the north-star test from CLAUDE.md applied literally: *would this still work on a
 *     survey nobody here has ever seen?* These pages are not our corpus, they are not
 *     generated by our engine, and the arm is required to NAME what it cannot handle
 *     rather than return an empty finding list.
 *
 *   node graph-spike/arm/selftest.mjs
 */


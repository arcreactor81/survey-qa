// ══════════════════════════════════════════════════════════ A. UNIT ══

function irWith(overrides = {}) {
  const ir = emptyIR({ ingester: "selftest", surveyId: "T" });
  Object.assign(ir, overrides);
  return ir;
}

function unitTests() {
  // ---- L1 piping ------------------------------------------------------------------
  {
    const ir = irWith({ questions: [{ id: "Q3", options: [], rules: [], __basis: { text: "stated" } }] });
    const { guards, report } = makeLeakGuards(ir);
    const g1 = guards.pipingBeforeText({ documented: "How satisfied are you with {Q2drug}?", observed: "How satisfied are you with OZEMPIC?" });
    ok("L1 downgrades when the DOCUMENT side still holds an unresolved pipe token", g1.action === "downgrade", g1.reason);
    const g2 = guards.pipingBeforeText({ documented: "How satisfied are you with OZEMPIC?", observed: "How satisfied are you with {Q2drug}?" });
    ok("L1 reclassifies to piping/raw-code-displayed when the SITE shows a literal token",
      g2.action === "reclassify" && g2.requirementClass === "piping" && g2.predicate === "raw-code-displayed", JSON.stringify(g2));
    const g3 = guards.pipingBeforeText({ documented: "A", observed: "B" });
    ok("L1 keeps an ordinary wording difference", g3.action === "keep");
    ok("L1 reports that it fired", report().find((r) => r.id === "L1").firedTimes === 2);
  }

  // ---- L2 carry-forward -------------------------------------------------------------
  {
    const ir = irWith({ questions: [{ id: "Q2", options: [], optionsFrom: { q: "Q1" } }, { id: "Q4", options: [] }] });
    const { guards, report } = makeLeakGuards(ir);
    ok("L2 downgrades 'never rendered' on a carry-forward node", guards.carryForwardAutoSkip("Q2").action === "downgrade");
    ok("L2 keeps 'never rendered' on an ordinary node", guards.carryForwardAutoSkip("Q4").action === "keep");
    ok("L2 reports that it fired", report().find((r) => r.id === "L2").firedTimes === 1);
  }

  // ---- L3 option order --------------------------------------------------------------
  {
    const ir = irWith({
      questions: [
        { id: "Q1", options: [], __basis: { optionOrder: "stated" } },
        { id: "Q2", options: [], randomize: { mode: "shuffle" }, __basis: { optionOrder: "stated" } },
        { id: "Q3", options: [], __basis: { optionOrder: "unknown" } },
      ],
    });
    const { guards, report } = makeLeakGuards(ir);
    ok("L3 keeps an order defect where the document states a fixed order", guards.optionOrderComparable("Q1").action === "keep");
    ok("L3 downgrades where the document permits randomisation", guards.optionOrderComparable("Q2").action === "downgrade");
    ok("L3 downgrades where the document says nothing about order", guards.optionOrderComparable("Q3").action === "downgrade");
    ok("L3 reports that it fired", report().find((r) => r.id === "L3").firedTimes === 2);
  }

  // ---- L4 validation/routing separation --------------------------------------------
  {
    const { guards } = makeLeakGuards(irWith({ questions: [] }));
    const clean = guards.assertValidationSeparated(new Set(["Q1|code=3"]), [{ at: "Q2", classKey: "code=1" }]);
    ok("L4 holds when no routing finding sits on an inadmissible edge", clean.ok);
    const { guards: g2 } = makeLeakGuards(irWith({ questions: [] }));
    const dirty = g2.assertValidationSeparated(new Set(["Q1|code=3"]), [{ at: "Q1", classKey: "code=3" }]);
    ok("L4 FAILS when a routing finding sits on an edge the document forbids — the assertion is not vacuous",
      dirty.ok === false && dirty.violations.length === 1, JSON.stringify(dirty.violations));
  }

  // ---- L5 resync --------------------------------------------------------------------
  {
    const { guards } = makeLeakGuards(irWith({ questions: [] }));
    const s = guards.recordResync({ findings: [1, 2, 3, 4, 5, 6, 7], resyncsUsed: 67, resyncFailures: 10 }, { findings: [1] });
    ok("L5 measures what resync recovered", s.hiddenByFirstDivergence === 6, `recovered ${s.hiddenByFirstDivergence}`);
  }

  // ---- basis gate ------------------------------------------------------------------
  {
    const ir = irWith({
      __basis: { fallThrough: "inferred", routing: "stated", questionText: "unknown", optionSet: "lower-bound" },
      questions: [{ id: "Q1", options: [], rules: [{ if: { q: "Q1", op: "eq", value: 2 }, goto: "Q5", __basis: "stated" }] }],
    });
    ok("edgeBasis: a stated rule is stated", edgeBasis(ir, "Q1", "Q5") === "stated");
    ok("edgeBasis: an unstated target is the INFERRED fall-through", edgeBasis(ir, "Q1", "Q2") === "inferred");
    ok("attributeBasis: unknown question text is unknown", attributeBasis(ir, "Q1", "text") === "unknown");
    ok("attributeBasis: a lower-bound option set is not 'stated'", attributeBasis(ir, "Q1", "options") === "lower-bound");
  }

  // ---- the basis gate actually suppresses a defect ----------------------------------
  {
    const ir = irWith({
      __basis: { fallThrough: "inferred", routing: "stated", questionText: "unknown", optionSet: "lower-bound", optionOrder: "unknown" },
      questions: [{ id: "Q1", options: [], rules: [] }],
    });
    const { guards } = makeLeakGuards(ir);
    const m = makeMapper({ ir, graphS: { nodes: {} }, guards, surveyId: "T" });
    m.fromLevelC({ findings: [{ kind: "TEXT-MISMATCH", at: "Q1", documented: null, observed: "anything" }] });
    ok("a wording comparison with no stated document text emits NO defect",
      m.findings.filter((f) => f.claimClass === "defect").length === 0);
    m.emitDowngradeObservations();
    ok("...and emits an observation instead, so it is not a silent drop",
      m.findings.some((f) => f.claimClass === "observation" && /not asserted as defects/i.test(f.prose)));
  }

  // ---- a STATED comparison still produces a defect (the gate is not a blanket mute) --
  {
    const ir = irWith({ __basis: { questionText: "stated" }, questions: [{ id: "Q1", options: [], rules: [], __basis: { text: "stated" } }] });
    const { guards } = makeLeakGuards(ir);
    const m = makeMapper({ ir, graphS: { nodes: {} }, guards, surveyId: "T" });
    m.fromLevelC({ findings: [{ kind: "TEXT-MISMATCH", at: "Q1", documented: "A", observed: "B" }] });
    ok("a wording comparison WITH stated document text does produce a defect",
      m.findings.filter((f) => f.claimClass === "defect" && f.requirementClass === "wording").length === 1);
  }

  // ---- route classification ---------------------------------------------------------
  {
    ok("terminate not triggered", classifyRoute("END:terminated", "Q5")[1] === "terminate-not-triggered");
    ok("terminate triggered unexpectedly", classifyRoute("Q5", "END:terminated")[1] === "terminate-triggered-unexpectedly");
    ok("ordinary mis-route", classifyRoute("Q5", "Q6").join("/") === "routing/route-destination-differs");
  }

  // ---- identifier alignment (DOC-01) -------------------------------------------------
  {
    const ir = irWith({ questions: [{ id: "Q1", options: [], rules: [{ if: {}, goto: "Q2" }] }, { id: "Q2", options: [] }] });
    const a = alignIdentifiers(ir, { nodes: { "q 1": {}, Q2: {} } });
    ok("alignment canonicalises a differently-spelled identifier", a.renamed.length === 1 && ir.questions[0].id === "q 1", JSON.stringify(a.renamed));
    ok("...and rewrites the rule target with it", ir.questions[0].rules[0].goto === "Q2");

    const ir2 = irWith({ questions: [{ id: "Q1", options: [] }] });
    const a2 = alignIdentifiers(ir2, { nodes: { QUESTION_ONE: {} } });
    ok("alignment reports a total namespace mismatch rather than merging", a2.matched.length === 0 && a2.overlap === 0);
  }

  // ---- IR validation is fail-closed --------------------------------------------------
  {
    ok("IR with a dangling goto is rejected",
      validateIR({ ...irWith({ questions: [{ id: "Q1", options: [], rules: [{ goto: "Q9" }] }] }) }).ok === false);
    ok("IR with a duplicate question id is rejected",
      validateIR({ ...irWith({ questions: [{ id: "Q1", options: [] }, { id: "Q1", options: [] }] }) }).ok === false);
    ok("IR with an absent option list is ACCEPTED (a numeric question has none)",
      validateIR({ ...irWith({ questions: [{ id: "Q1" }] }) }).ok === true);
  }
}


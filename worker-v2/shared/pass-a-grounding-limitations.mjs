/**
 * Closed, metadata-only wire for primary Pass-A rows that could not be grounded.
 *
 * The submitted document remains authoritative. A candidate that cannot bind to its exact
 * owning source may not become a requirement or coverage credit, but its omission must remain
 * counted and visible. This codec carries only coordinates and closed machine reasons: never
 * a quote, model output, candidate statement, or provider response.
 */

export const PASS_A_PRIMARY_GROUNDING_LIMITATION_KIND =
  "pass-a-primary-candidate-ungrounded";
export const PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND =
  "pass-a-primary-grounding-limitations/1.0.0";
export const SOURCE_GROUNDING_BLOCKER_KIND = "DOCUMENT_SOURCE_GROUNDING_INCOMPLETE";
export const PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_PREFIX =
  "PASS_A_PRIMARY_GROUNDING_LIMITATIONS: ";

const PASS_A_HASH = /^sha256:[0-9a-f]{64}$/;
const PASS_A_WINDOW = /^A-w([1-9]\d*)$/;
// Pass-A source ids are generated by the document parser, not supplied by the model. Keeping
// their wire grammar closed prevents a source quote or model string from being laundered into
// the one metadata field this public detail is allowed to reproduce.
const SOURCE_BLOCK_ID = /^b\d{4,}$/;
const ROW_KINDS = ["global-rule", "cross-reference", "ambiguity", "unverifiable"];
const ROW_KIND_ORDER = new Map(ROW_KINDS.map((kind, index) => [kind, index]));
const ROW_KIND_LABELS = new Map([
  ["global-rule", "global rule"],
  ["cross-reference", "cross-reference"],
  ["ambiguity", "ambiguity"],
  ["unverifiable", "unverifiable item"],
]);
const REASONS = new Set([
  "source-block-ownership-invalid",
  "source-quote-not-exact",
  "source-evidence-set-invalid",
  "grounded-row-linkage-incomplete",
  "structural-validation-failed",
]);
const REASON_DETAILS = new Map([
  [
    "source-block-ownership-invalid",
    "one or more claimed block IDs were outside that extraction unit, or no usable owned block was available",
  ],
  [
    "source-quote-not-exact",
    "the claimed evidence was not one exact excerpt from an owned source block",
  ],
  [
    "source-evidence-set-invalid",
    "the claimed block set and evidence set did not identify the same owned source",
  ],
  [
    "grounded-row-linkage-incomplete",
    "a required grounded companion row was unavailable",
  ],
  [
    "structural-validation-failed",
    "the model output row failed structural validation and could not be decoded",
  ],
]);
// These independent caps bound the public report even when a retained run contains many
// rejected rows or one rejected row owns many blocks. Exact omitted counts remain visible.
const DETAIL_ROW_LIMIT = 5;
const DETAIL_SOURCE_BLOCK_LIMIT = 4;
const ROW_KEYS = [
  "kind",
  "reason",
  "rowIndex",
  "rowKind",
  "sourceBlockIds",
  "unit",
].sort();
const SUPPLEMENT_KEYS = ["kind", "passAHash", "rows"].sort();

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const plural = (count, singular, pluralForm = `${singular}s`) =>
  count === 1 ? singular : pluralForm;

function exactKeys(value, expected) {
  const actual = Object.keys(value).sort();
  return actual.length === expected.length &&
    actual.every((key, index) => key === expected[index]);
}

function closedText(value, field) {
  if (typeof value !== "string" || value.length === 0 || value.trim() !== value || value.length > 240) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: ${field} must be a closed non-empty string`,
    );
  }
  return value;
}

/** Unknown fields refuse rather than becoming accidental public/model-output channels. */
export function validatePassAPrimaryGroundingLimitation(value) {
  if (!isObject(value) || !exactKeys(value, ROW_KEYS)) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: expected exactly [${ROW_KEYS.join(", ")}]`,
    );
  }
  if (value.kind !== PASS_A_PRIMARY_GROUNDING_LIMITATION_KIND) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: unsupported kind ${String(value.kind)}`,
    );
  }
  const unit = closedText(value.unit, "unit");
  if (unit !== "A" && !PASS_A_WINDOW.test(unit)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: unit must be A or A-w<positive>");
  }
  if (!ROW_KIND_ORDER.has(value.rowKind)) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: rowKind must be one of ${ROW_KINDS.join(", ")}`,
    );
  }
  if (!Number.isSafeInteger(value.rowIndex) || value.rowIndex < 1) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: rowIndex must be 1-based");
  }
  if (!Array.isArray(value.sourceBlockIds)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sourceBlockIds must be an array");
  }
  const sourceBlockIds = value.sourceBlockIds.map((id, index) =>
    closedText(id, `sourceBlockIds[${index}]`)
  );
  if (sourceBlockIds.some((id) => !SOURCE_BLOCK_ID.test(id))) {
    throw new TypeError(
      "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sourceBlockIds must contain only internal Pass-A block identifiers",
    );
  }
  if (new Set(sourceBlockIds).size !== sourceBlockIds.length) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sourceBlockIds must be unique");
  }
  if (!REASONS.has(value.reason)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: reason is not a closed grounding code");
  }
  return {
    kind: PASS_A_PRIMARY_GROUNDING_LIMITATION_KIND,
    unit,
    rowKind: value.rowKind,
    rowIndex: value.rowIndex,
    sourceBlockIds,
    reason: value.reason,
  };
}

function coordinates(row) {
  return [
    row.unit === "A" ? 1 : Number(PASS_A_WINDOW.exec(row.unit)[1]),
    ROW_KIND_ORDER.get(row.rowKind),
    row.rowIndex,
  ];
}

function compareCoordinates(left, right) {
  const a = coordinates(left);
  const b = coordinates(right);
  for (let index = 0; index < a.length; index += 1) {
    if (a[index] !== b[index]) return a[index] - b[index];
  }
  return 0;
}

/** Validate the complete array and require deterministic window/kind/row order. */
export function validatePassAPrimaryGroundingLimitations(value) {
  if (!Array.isArray(value)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: limitations must be an array");
  }
  const rows = value.map(validatePassAPrimaryGroundingLimitation);
  for (let index = 1; index < rows.length; index += 1) {
    if (compareCoordinates(rows[index - 1], rows[index]) >= 0) {
      throw new TypeError(
        "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: rows are duplicate or not in deterministic window/row order",
      );
    }
  }
  return rows;
}

/** Missing is unknown, never an attested zero. */
export function primaryGroundingLimitationsFromPassAPayload(payload) {
  if (!isObject(payload) || !Object.prototype.hasOwnProperty.call(payload, "primaryGroundingLimitations")) {
    throw new TypeError(
      "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: primaryGroundingLimitations was not evaluated",
    );
  }
  return validatePassAPrimaryGroundingLimitations(payload.primaryGroundingLimitations);
}

/** Always emitted, including rows=[], so current seals distinguish evaluated zero from omission. */
export function primaryGroundingLimitationsSupplement(value, passAHash) {
  const rows = validatePassAPrimaryGroundingLimitations(value);
  if (typeof passAHash !== "string" || !PASS_A_HASH.test(passAHash)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: supplement passAHash is malformed");
  }
  return `${PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_PREFIX}${JSON.stringify({
    kind: PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND,
    passAHash,
    rows,
  })}`;
}

/** Null means unrelated. A named-but-malformed supplement throws. */
export function parsePrimaryGroundingLimitationsSupplement(value) {
  if (typeof value !== "string" || !value.startsWith(PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_PREFIX)) return null;
  let parsed;
  try {
    parsed = JSON.parse(value.slice(PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_PREFIX.length));
  } catch (error) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed supplement JSON is malformed (${String(error)})`,
    );
  }
  if (!isObject(parsed) || !exactKeys(parsed, SUPPLEMENT_KEYS)) {
    throw new TypeError(
      `PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed supplement expected exactly [${SUPPLEMENT_KEYS.join(", ")}]`,
    );
  }
  if (parsed.kind !== PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed supplement kind is unsupported");
  }
  if (typeof parsed.passAHash !== "string" || !PASS_A_HASH.test(parsed.passAHash)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed supplement passAHash is malformed");
  }
  return {
    kind: PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND,
    passAHash: parsed.passAHash,
    rows: validatePassAPrimaryGroundingLimitations(parsed.rows),
  };
}

/**
 * Positive immutable lineage check for whether absence is legacy or a deleted current marker.
 *
 * `primaryGroundingLimitationsVersion` is a new semantic extraction field introduced with this
 * wire. Its exact value requires the marker; absence positively identifies a pre-wire revision,
 * including deployed model revisions that already carried reuseInputsHash. Human-authored 1.1
 * revisions never run Pass A. Unknown present values refuse rather than being guessed historical.
 */
export function primaryGroundingMarkerRequiredForRevision(revision) {
  if (!isObject(revision) || !isObject(revision.extraction)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed revision lineage is missing");
  }
  const extraction = revision.extraction;
  if (
    revision.schemaVersion === "v2-contract-revision/1.1.0" &&
    extraction.method === "human-authored" &&
    extraction.reuseInputsHash === null &&
    extraction.passAHash === null
  ) return false;

  if (revision.schemaVersion !== "v2-contract-revision/1.0.0") {
    throw new TypeError(
      "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: revision is not a recognized historical or current model lineage",
    );
  }
  if (!Object.prototype.hasOwnProperty.call(extraction, "primaryGroundingLimitationsVersion")) {
    // Positively identified by absence of a field that did not exist before this wire, not
    // merely by failure to find the supplement it requires.
    return false;
  }
  if (
    extraction.primaryGroundingLimitationsVersion !== PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND ||
    typeof extraction.passAHash !== "string" ||
    !PASS_A_HASH.test(extraction.passAHash)
  ) {
    throw new TypeError(
      "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: current grounding-marker lineage is malformed or unsupported",
    );
  }
  return true;
}

/**
 * Historical revisions may have no marker only when immutable lineage positively identifies
 * them. Current marker deletion, duplicates, malformed rows, or a foreign hash refuse closed.
 */
export function contractPrimaryGroundingLimitations(supplements, expectedPassAHash, revision) {
  if (!Array.isArray(supplements)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: contractSupplements must be an array");
  }
  const markerRequired = primaryGroundingMarkerRequiredForRevision(revision);
  const found = [];
  for (const supplement of supplements) {
    const decoded = parsePrimaryGroundingLimitationsSupplement(supplement);
    if (decoded !== null) found.push(decoded);
  }
  if (found.length > 1) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: duplicate sealed grounding supplements");
  }
  if (found.length === 0) {
    if (markerRequired) {
      throw new TypeError(
        "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: current model revision is missing its required grounding marker",
      );
    }
    return null;
  }
  if (
    !PASS_A_HASH.test(expectedPassAHash ?? "") ||
    revision.extraction.passAHash !== expectedPassAHash ||
    found[0].passAHash !== expectedPassAHash
  ) {
    throw new TypeError(
      "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed supplement does not bind the revision's exact Pass-A hash",
    );
  }
  return found[0];
}

export function primaryGroundingLimitationDetail(value) {
  if (!isObject(value) || !exactKeys(value, SUPPLEMENT_KEYS)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed limitation envelope is malformed");
  }
  if (value.kind !== PASS_A_PRIMARY_GROUNDING_SUPPLEMENT_KIND) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: sealed limitation kind is unsupported");
  }
  if (typeof value.passAHash !== "string" || !PASS_A_HASH.test(value.passAHash)) {
    throw new TypeError("PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: limitation Pass-A hash is malformed");
  }
  const rows = validatePassAPrimaryGroundingLimitations(value.rows);
  const units = new Set(rows.map((row) => row.unit)).size;
  const displayedRows = rows.slice(0, DETAIL_ROW_LIMIT);
  const hiddenRows = rows.length - displayedRows.length;
  const rowDetails = displayedRows.map((row) => {
    const rowKindLabel = ROW_KIND_LABELS.get(row.rowKind);
    const reasonDetail = REASON_DETAILS.get(row.reason);
    if (rowKindLabel === undefined || reasonDetail === undefined) {
      throw new TypeError(
        "PASS_A_PRIMARY_GROUNDING_LIMITATION_INVALID: public detail vocabulary is incomplete",
      );
    }
    const displayedSourceBlockIds = row.sourceBlockIds.slice(0, DETAIL_SOURCE_BLOCK_LIMIT);
    const hiddenSourceBlockIds = row.sourceBlockIds.length - displayedSourceBlockIds.length;
    const sourceBlocks = displayedSourceBlockIds.length === 0
      ? "none"
      : displayedSourceBlockIds.join(", ");
    const sourceRemainder = hiddenSourceBlockIds > 0
      ? (
        ` (${hiddenSourceBlockIds} more source block ` +
        `${plural(hiddenSourceBlockIds, "ID")} retained for this row)`
      )
      : "";
    return (
      `${row.unit}; ${rowKindLabel} row ${row.rowIndex}; ` +
      `owned source block IDs: ${sourceBlocks}${sourceRemainder}; ` +
      `reason ${row.reason}: ${reasonDetail}.`
    );
  });
  const displayScope = rows.length === 0
    ? "No affected row metadata is retained."
    : (
      `Affected row metadata (${displayedRows.length === rows.length
        ? `all ${rows.length} retained ${plural(rows.length, "row")}`
        : `first ${displayedRows.length} of ${rows.length} retained rows`}, ` +
      `ordered by unit, row kind, and row number): ` +
      rowDetails.join(" ")
    );
  const retainedRemainder = rows.length === 0
    ? "No affected rows exist for this evaluated marker."
    : hiddenRows > 0
    ? (
      `${hiddenRows} additional affected ${plural(hiddenRows, "row")} ` +
      `${hiddenRows === 1 ? "is" : "are"} retained in the sealed run record and ` +
      `${hiddenRows === 1 ? "is" : "are"} not displayed here.`
    )
    : `All ${rows.length} affected ${plural(rows.length, "row")} ${rows.length === 1 ? "is" : "are"} displayed.`;
  return (
    `${SOURCE_GROUNDING_BLOCKER_KIND}: ${rows.length} primary candidate ${plural(rows.length, "row")} ` +
    `across ${units} Pass-A ${plural(units, "unit")} ` +
    `could not be bound to exact submitted-document evidence and received no requirement or coverage credit. ` +
    `${displayScope} ${retainedRemainder} ` +
    `Provenance bridge: exact retained Pass-A payload ${value.passAHash}. ` +
    "The sealed rows contain only unit coordinates, source-block identifiers, and closed grounding reasons; " +
    "no model claim or source quote is reproduced."
  );
}
